export const archById = Object.fromEntries(
  archComponents.map((c) => [c.id, c]),
) as Record<string, ArchComponent>

export function getFocusSet(selectedId: string | null) {
  if (!selectedId) {
    return { selected: null as string | null, upstream: new Set<string>(), downstream: new Set<string>() }
  }
  const c = archById[selectedId]
  if (!c) {
    return { selected: null as string | null, upstream: new Set<string>(), downstream: new Set<string>() }
  }
  return {
    selected: selectedId,
    upstream: new Set(c.dependsOn),
    downstream: new Set(c.next),
  }
}
